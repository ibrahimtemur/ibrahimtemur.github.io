const STORAGE_LANG_KEY = "portfolio_lang";
let activeLang = (typeof localStorage !== "undefined" && localStorage.getItem(STORAGE_LANG_KEY)) || "tr";
if (activeLang !== "tr" && activeLang !== "en") activeLang = "tr";

const langSubscribers = new Set();

/**
 * Returns the active interface language ('tr' | 'en').
 */
export function getActiveLang() {
  return activeLang;
}

/**
 * Looks up a translation key in the active dictionary, falling back to 'tr' then key.
 */
export function t(key, lang = activeLang) {
  const target = lang === "en" ? "en" : "tr";
  if (I18N[target] && I18N[target][key] !== undefined) {
    return I18N[target][key];
  }
  if (I18N.tr && I18N.tr[key] !== undefined) {
    return I18N.tr[key];
  }
  return key;
}

/**
 * Subscribes a listener to language changes. Returns an unsubscribe function.
 */
export function onLanguageChange(callback) {
  if (typeof callback === "function") {
    langSubscribers.add(callback);
  }
  return () => langSubscribers.delete(callback);
}

/**
 * Applies language across document metadata, [data-i18n] nodes, and listeners.
 */
export function applyLanguage(lang) {
  activeLang = lang === "en" ? "en" : "tr";
  try {
    localStorage.setItem(STORAGE_LANG_KEY, activeLang);
  } catch (_) {
    /* ignore storage failures */
  }

  document.documentElement.setAttribute("lang", activeLang);
  const dict = I18N[activeLang];
  if (dict["meta.title"]) {
    document.title = dict["meta.title"];
  }

  const trBtn = document.getElementById("langTrBtn");
  const enBtn = document.getElementById("langEnBtn");
  if (trBtn && enBtn) {
    trBtn.classList.toggle("active", activeLang === "tr");
    enBtn.classList.toggle("active", activeLang === "en");
    trBtn.setAttribute("aria-pressed", String(activeLang === "tr"));
    enBtn.setAttribute("aria-pressed", String(activeLang === "en"));
  }

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (key && dict[key] !== undefined) {
      el.innerHTML = dict[key];
    }
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (key && dict[key] !== undefined) {
      el.setAttribute("placeholder", dict[key]);
    }
  });

  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    const key = el.getAttribute("data-i18n-aria");
    if (key && dict[key] !== undefined) {
      el.setAttribute("aria-label", dict[key]);
    }
  });

  langSubscribers.forEach((cb) => {
    try {
      cb(activeLang);
    } catch (_) {
      /* isolate subscriber errors */
    }
  });

  window.dispatchEvent(new CustomEvent("portfolio:langchange", { detail: { lang: activeLang } }));
  return activeLang;
}

/**
 * Initializes language buttons and applies initial language.
 */
export function initI18n() {
  document.querySelectorAll(".lang-btn").forEach((btn) => {
    btn.addEventListener("click", () => {
      const targetLang = btn.getAttribute("data-lang");
      if (targetLang && targetLang !== activeLang) {
        applyLanguage(targetLang);
      }
    });
  });

  applyLanguage(activeLang);
  return activeLang;
}
